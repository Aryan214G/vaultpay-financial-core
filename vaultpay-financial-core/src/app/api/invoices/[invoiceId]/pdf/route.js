import { NextResponse } from "next/server";
import PDFDocument from "pdfkit";

import { adminDb } from "@/lib/firebase-admin";
import { requireAuth } from "@/lib/require-auth";

export async function GET(request, { params }) {
  const authResult = await requireAuth(request);

  if (authResult.error) {
    return NextResponse.json(
      { error: authResult.error },
      { status: authResult.status }
    );
  }

  const { invoiceId } = await params;

  try {
    const invoiceDoc = await adminDb
      .collection("invoices")
      .doc(invoiceId)
      .get();

    if (!invoiceDoc.exists) {
      return NextResponse.json(
        { error: "Invoice not found." },
        { status: 404 }
      );
    }

    const invoice = {
      id: invoiceDoc.id,
      ...invoiceDoc.data(),
    };

    if (
      authResult.role === "client" &&
      invoice.clientId !== authResult.uid
    ) {
      return NextResponse.json(
        { error: "You do not have permission to download this invoice." },
        { status: 403 }
      );
    }

    const pdf = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Title: `Invoice ${invoice.invoiceNumber || invoice.id}`,
        Author: "VaultPay",
      },
    });

    const chunks = [];

    pdf.on("data", (chunk) => chunks.push(chunk));

    const pdfBufferPromise = new Promise((resolve, reject) => {
      pdf.on("end", () => resolve(Buffer.concat(chunks)));
      pdf.on("error", reject);
    });

    pdf.fontSize(12).fillColor("#2563eb").text("VAULTPAY");
    pdf.moveDown(0.5);

    pdf.fontSize(24).fillColor("#18181b").text("INVOICE");
    pdf.moveDown();

    pdf.fontSize(12).fillColor("#52525b");
    pdf.text(`Invoice number: ${invoice.invoiceNumber || invoice.id}`);
    pdf.text(`Description: ${invoice.description || "—"}`);
    pdf.text(`Billed to: ${invoice.clientEmail || "—"}`);
    pdf.text(`Due date: ${invoice.dueDate || "—"}`);
    pdf.text(`Status: ${invoice.status || "Pending"}`);

    pdf.moveDown();
    pdf.fontSize(16).fillColor("#18181b");
    pdf.text(
      `Amount: ${new Intl.NumberFormat("en-US", {
        style: "currency",
        currency: "USD",
      }).format(invoice.amount)}`
    );

    pdf.moveDown(2);
    pdf.fontSize(9).fillColor("#71717a");
    pdf.text("Generated by VaultPay Financial Core.");

    pdf.end();

    const pdfBuffer = await pdfBufferPromise;
    const safeInvoiceNumber = String(
      invoice.invoiceNumber || invoice.id
    ).replace(/[^a-zA-Z0-9_-]/g, "_");

    return new Response(new Uint8Array(pdfBuffer), {
      status: 200,
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="invoice-${safeInvoiceNumber}.pdf"`,
        "Cache-Control": "private, no-store",
      },
    });
  } catch (error) {
    console.error("Failed to generate invoice PDF:", error);

    return NextResponse.json(
      { error: "Failed to generate invoice PDF." },
      { status: 500 }
    );
  }
}
